/**
 * Normalizes any circle name or raw ID to its official circle ID
 */
export function normalizeCircleId(raw?: string): string {
  if (!raw) return 'circle_othman';
  const clean = raw.trim();
  if (CIRCLE_NAME_TO_ID_MAP[clean]) {
    return CIRCLE_NAME_TO_ID_MAP[clean];
  }
  const withoutPrefix = clean.replace(/^حلقة\s+/, '').trim();
  if (CIRCLE_NAME_TO_ID_MAP[withoutPrefix]) {
    return CIRCLE_NAME_TO_ID_MAP[withoutPrefix];
  }
  return clean;
}

